"""
tasks.py - the Pydantic output schema, the three tasks and the crew.

The schema, task descriptions and crew setup are copied word-for-word from
the Colab notebook. Only the imports changed (the agents now come from
agents.py).

Note: app.py runs one generation at a time (a lock), because these task
objects keep their results after a run and must not be shared by two
requests at once.
"""

from typing import List

from crewai import Crew, Process, Task
from pydantic import BaseModel, Field

from agents import content_ideator, engagement_optimizer, script_writer


# Implementing Pydantic Output Schema
class ReelScene(BaseModel):
    scene_number: int
    timestamp: str
    duration_seconds: int
    visual_direction: str
    character_action: str
    dialogue: str
    text_overlay: str
    audio_effect: str
    transition: str


class PerformanceReview(BaseModel):
    hook_strength: str
    audience_relatability: str
    theme_relevance: str
    retention_improvements: str


class EngagementCTAs(BaseModel):
    comment_cta: str
    share_cta: str
    save_follow_cta: str


class PostingRecommendations(BaseModel):
    suggested_posting_window: str
    audience_targeting: str
    instagram_insights_tip: str


class ReelPackage(BaseModel):
    reel_title: str
    total_duration_seconds: int
    performance_review: PerformanceReview
    scenes: List[ReelScene]
    editing_instructions: str
    caption: str
    hashtags: List[str] = Field(min_length=15, max_length=20)
    engagement_ctas: EngagementCTAs
    posting_recommendations: PostingRecommendations


# Assigning Task for Content Ideator
task_ideate = Task(
    description="""
    The user's Reel theme is: {reel_theme}
    Target audience: {target_audience}
    Content goal: {content_goal}
    Reel duration: {duration_seconds} seconds

    1. Generate 3 creative and engaging Reel concepts.
    2. Select the most suitable concept.
    3. Explain its format and visual approach.
    4. Suggest a suitable audio style.
    5. Explain why the audience will connect with it.

    Output format:
    ## Reel Concept
    - Theme:
    - Three Concepts:
    - Selected Concept:
    - Format:
    - Audio Style:
    - Target Emotion:
    - Why It Will Work:
    """,
    expected_output="A structured Markdown document containing three Reel concepts and one selected concept.",
    agent=content_ideator,
    output_pydantic=ReelPackage
)


# Assigning Task for Script Writer
task_write_script = Task(
    description="""
    You are given the Reel concept generated by the Content Ideator.

    User Requirements:
    - Target audience: {target_audience}
    - Maximum Reel duration: {duration_seconds} seconds
    - Content goal: {content_goal}

    YOUR TASK:
    Transform the selected Reel concept into a creative,
    engaging and COMPLETE shot-by-shot Instagram Reel script.

    SCRIPT REQUIREMENTS:

    1. OPENING HOOK:
       - Capture attention within the first 1-2 seconds.
       - Use a powerful dialogue, question, surprising action
         or relatable situation.
       - Include the exact dialogue or on-screen text.

    2. MAIN CONTENT:
       - Divide the Reel into 3-5 meaningful shots.
       - Give every shot a specific timestamp and duration.
       - Describe character actions, expressions and movements.
       - Include camera angles, movements and framing.
       - Write exact dialogues or voiceovers.
       - Suggest short and readable text overlays.
       - Include suitable background music or sound effects.

    3. STORYTELLING:
       - Maintain a clear beginning, middle and ending.
       - Build curiosity and maintain audience attention.
       - Use natural, conversational dialogues.
       - Make the content relatable to the target audience.
       - Ensure smooth transitions between shots.

    4. FINAL SHOT:
       - End with a memorable punchline, surprise,
         emotional payoff or meaningful CTA.
       - Make the ending satisfying and engaging.

    5. EDITING DIRECTIONS:
       - Suggest practical transitions between shots.
       - Include cuts, zooms, camera movements or effects
         wherever they improve storytelling.
       - Keep editing achievable using a smartphone.

    STRICT RULES:
       - Follow the concept selected by the Content Ideator.
       - Do not unnecessarily change the original concept.
       - Keep the total duration within {duration_seconds} seconds.
       - Ensure shot timestamps do not overlap or leave gaps.
       - Keep dialogues short, natural and engaging.
       - Every shot must contribute to the story.
       - Do not add unnecessary explanations.
       - Do not invent claims about trending audio.
       - Provide exact dialogue and text overlays, not vague suggestions.

    FINAL OUTPUT FORMAT:

    # Instagram Reel Script

    ## Reel Title:
    ## Total Duration:

    ## Shot-by-Shot Script:

    ### Shot 1 - Hook
    - Timestamp:
    - Duration:
    - Visual / Camera Direction:
    - Character Action:
    - Exact Dialogue / Voiceover:
    - Text Overlay:
    - Audio / Sound Effect:
    - Transition:

    ### Shot 2 - Main Content
    [Use the same structure]

    ### Shot 3 - Main Content
    [Use the same structure]

    ### Final Shot - Punchline / CTA
    [Use the same structure]

    ## Final Editing Instructions:

    IMPORTANT:
    Return ONLY the complete, ready-to-shoot Reel script.
    Do not include your reasoning, analysis or introduction.
    """,

    expected_output=(
        "A complete, production-ready Instagram Reel script "
        "with timestamped shots, exact dialogues, character actions, "
        "camera directions, text overlays, audio suggestions, "
        "transitions and final editing instructions."
    ),

    agent=script_writer,
    context=[task_ideate],
    output_pydantic=ReelPackage
)


# Assigning Task for Engagement Optimizer
task_optimize = Task(
    description="""
    You are the final quality-control and Instagram growth
    optimization agent in the InstaPilot AI workflow.

    USER REQUIREMENTS:
    - Original Reel theme: {reel_theme}
    - Target audience: {target_audience}
    - Content goal: {content_goal}
    - Maximum duration: {duration_seconds} seconds

    You will receive:
    1. The original Reel concept from the Content Ideator.
    2. The complete Reel script from the Script Writer.

    YOUR RESPONSIBILITIES:

    1. REEL PERFORMANCE ANALYSIS:
       - Evaluate the opening hook.
       - Check audience relatability.
       - Identify weak or unnecessary scenes.
       - Review storytelling and pacing.
       - Check whether the Reel fulfills the original theme.
       - Identify opportunities to improve retention.

    2. SCRIPT OPTIMIZATION:
       - Improve weak dialogues and visual moments.
       - Strengthen the opening hook.
       - Improve scene transitions and storytelling.
       - Maintain natural and conversational language.
       - Preserve the original selected concept.
       - Ensure the script remains within the requested duration.
       - Do not introduce unrelated ideas.

    3. INSTAGRAM CAPTION:
       - Write an engaging and natural caption.
       - Start with an attention-grabbing opening.
       - Connect the caption with the Reel's theme.
       - Use appropriate emojis.
       - Encourage meaningful audience interaction.

    4. HASHTAG STRATEGY:
       - Generate 15-20 relevant hashtags.
       - Include niche-specific hashtags.
       - Include topic-specific hashtags.
       - Include relevant Indian audience hashtags.
       - Avoid unrelated or misleading hashtags.

    5. CALL TO ACTION:
       - Suggest one comment CTA.
       - Suggest one share CTA.
       - Suggest one save or follow CTA.
       - Keep CTAs natural and relevant.

    6. POSTING RECOMMENDATIONS:
       - Suggest a reasonable posting window in IST.
       - Explain that the recommendation is a starting point,
         not a guaranteed peak time.
       - Recommend checking the creator's Instagram Insights.
       - Suggest practical audience-targeting ideas.

    STRICT RULES:
       - The original user theme must remain the central focus.
       - Do not change the selected concept unnecessarily.
       - Do not invent current Instagram trends or trending audio.
       - Do not guarantee views, followers or viral performance.
       - Do not make unsupported claims about audience behavior.
       - Keep the final script consistent with the original concept.
       - Ensure all timestamps fit the requested duration.
       - Do not omit important scenes from the original script.

    FINAL OUTPUT FORMAT:

    # Final Instagram Reel Package

    ## 1. Reel Performance Review
    - Hook Strength:
    - Audience Relatability:
    - Theme Relevance:
    - Retention Improvements:
    - Suggested Changes:

    ## 2. Final Optimized Reel Script
    - Reel Title:
    - Total Duration:
    - Complete Shot-by-Shot Script:
    - Dialogues / Voiceovers:
    - Camera Directions:
    - Text Overlays:
    - Audio / Sound Effects:
    - Transitions:
    - Final Editing Instructions:

    ## 3. Instagram Caption
    - Attention-grabbing opening
    - Caption body
    - Relevant emojis

    ## 4. Hashtag Strategy
    - 15-20 relevant hashtags

    ## 5. Engagement CTAs
    - Comment CTA:
    - Share CTA:
    - Save / Follow CTA:

    ## 6. Posting Recommendations
    - Suggested Posting Window (IST):
    - Audience Targeting:
    - Instagram Insights Recommendation:

    ## 7. Final Quality Checklist
    - Theme relevance
    - Strong opening hook
    - Clear storytelling
    - Appropriate duration
    - Engaging caption
    - Relevant hashtags
    - Clear CTAs

    IMPORTANT:
    Return the complete final Reel publishing package.
    Do not include unnecessary reasoning or introductory text.
    """,

    expected_output=(
        "A complete, theme-relevant and optimized Instagram Reel "
        "publishing package containing performance analysis, "
        "the full optimized script, caption, 15-20 hashtags, "
        "engagement CTAs and posting recommendations."
    ),

    agent=engagement_optimizer,
    context=[task_ideate, task_write_script],
    output_pydantic=ReelPackage
)


# The crew: three agents, run one after another
reel_crew = Crew(
    agents = [content_ideator, script_writer, engagement_optimizer],
    tasks = [task_ideate, task_write_script, task_optimize],
    process = Process.sequential,
    verbose= True
)